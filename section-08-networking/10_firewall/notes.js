// What are firewall ?

    // A firewall is a network security system that monitors and controls incoming (inbound) and outgoing (outbound) traffic based on rules.

    // Types of Network Profiles

    //     Public Network
    //         Used in open/public places (e.g., coffee shop Wi-Fi)
    //         Most secure: strictest firewall rules

    //     Private Network
    //         For trusted networks (like home Wi-Fi)
    //         Less strict, allows device discovery

    //     Domain Network
    //         For office or enterprise networks (managed by organization)

    // Inbound vs Outbound Rules
    //     Type	    Default Behavior	Purpose
    //     Inbound	    Mostly blocked	    Controls external traffic coming in
    //     Outbound	Mostly allowed	    Controls internal traffic going out

    //     Rules can be set to allow/block specific ports, apps, or IP addresses.

    // DPI (Deep Packet Inspection)
    //     DPI is a technique used by advanced firewalls to inspect the contents of data packets (not just headers).
    //     Helps in blocking malicious, suspicious, or unauthorized content.